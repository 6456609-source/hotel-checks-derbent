import type { City } from "./cities";

export const getSeo = (city: City) => {
  const n = city.name;
  const i = city.in;
  const title = `Гостиничные чеки ${n} — отчётные документы за проживание в ${i} купить | Сделать документы о проживании в гостинице в ${i}`;
  const description = `Гостиничные чеки в ${i} и отчётные документы за проживание для командировки: кассовый чек, счёт, акт, договор. Принимает любая бухгалтерия для авансового отчёта, оплата наличными и по безналу. Поможем сделать документы о проживании в гостинице в ${i}. Чеки ${n} — быстро и официально.`;
  const keywords = [
    `гостиничные чеки ${n}`,
    `отчетные документы за проживание ${n}`,
    `отчётные документы за проживание в ${i}`,
    `гостиничные чеки в ${i}`,
    `чеки за гостиницу ${n}`,
    `чек за проживание в гостинице ${n}`,
    `документы за проживание ${n}`,
    `отчётные документы для командировки в ${city.to}`,
    `документы для авансового отчёта ${n}`,
    `закрывающие документы гостиница ${n}`,
    `гостиница с отчётными документами ${n}`,
    `чеки ${n}`,
    `гостиничные чеки ${n} купить`,
    `сделать документы о проживании в гостинице в ${i}`,
    ...(city.slug === "derbent" ? ["гостиничные чеки Махачкала"] : city.keywords ?? ["документы за проживание Дагестан"]),
  ].join(", ");
  return { title, description, keywords, image: city.photo };
};
